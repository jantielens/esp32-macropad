#include "display_perf.h"
#include <cassert>

int main() {
    DisplayPerfWindow window;
    DisplayPerfStats stats = {};
    window.reset(200);
    window.frames = 60;
    window.lv_timer.add(100);
    window.lv_timer.add(300);
    window.data_stream.add(50);
    window.screen_update.add(80);
    window.cycle.add(500);
    window.present.add(700);
    window.present.add(900);
    assert(!window.publish(1199, stats));
    assert(window.publish(1700, stats));
    assert(stats.fps == 40);
    assert(stats.lv_timer_us == 200 && stats.lv_timer_peak_us == 300);
    assert(stats.present_us == 800 && stats.present_peak_us == 900);
    assert(stats.data_stream_us == 50 && stats.screen_update_us == 80);
    assert(stats.cycle_us == 500 && stats.cycle_peak_us == 500);
    assert(window.publish(2700, stats));
    assert(stats.fps == 0 && stats.lv_timer_us == 0 && stats.present_peak_us == 0);
    window.frames = 10;
    window.reset(4000);
    assert(window.publish(5000, stats) && stats.fps == 0);
    window.reset(UINT32_MAX - 499);
    window.frames = 20;
    assert(window.publish(500, stats) && stats.fps == 20);
    window.frames = UINT32_MAX;
    assert(window.publish(1500, stats) && stats.fps == UINT16_MAX);

#if HAS_DISPLAY_DIAGNOSTICS
    DisplayRefreshTrace trace;
    trace.beginRefresh(0);
    trace.beginRender(100, 20, 5000);
    trace.endRender(800, 220, 5300);
    trace.endRefresh(1000);
    trace.beginRefresh(2000);
    trace.endRefresh(2500);
    assert(trace.stats.refresh_calls == 2 && trace.stats.render_calls == 1);
    assert(trace.stats.refresh_us == 1500 && trace.stats.render_us == 700);
    assert(trace.stats.render_flush_us == 200);
    assert(trace.stats.render_glyph_miss_us == 300);
    trace.stats.invalidations.add(100, 50, DisplayInvalidationSource::Timer);
    trace.stats.invalidations.add(100, 50, DisplayInvalidationSource::Timer);
    trace.stats.invalidations.add(20, 10, DisplayInvalidationSource::ScreenSwitch);
    assert(trace.stats.invalidations.requested_pixels == 10200);

    DisplayRenderSample sample;
    sample.completed_ms = 2000;
    sample.cycle_us = 6000000;
    sample.lv_timer_us = 5500000;
    sample.lv_timer_flush_us = 4000000;
    sample.screen_switched = true;
    sample.refresh = trace.stats;
    sample.glyphs = {uint64_t(1) << 34, 20, 10, 1, 300};
    sample.flush.add(1872 * 4, 10000);
    sample.flush.add(1872 * 4, 15000);
    window.render.add(sample);
    assert(window.publish(2500, stats));
    assert(stats.render.cycles == 1);
    assert(stats.render.navigations == 1 && stats.render.last_navigation.completed_ms == 2000);
    assert(stats.render.invalidations.calls[static_cast<unsigned>(DisplayInvalidationSource::Timer)] == 2);
    assert(stats.render.last.flush.calls == 2 && stats.render.last.flush.pixels == 14976);
    assert(stats.render.last.flush.total_us == 25000 && stats.render.last.flush.peak_us == 15000);
    assert(stats.render.last_navigation.glyphs.misses == 20);
    assert(stats.render.glyphs.hits == (uint64_t(1) << 34));
    assert(window.publish(3500, stats));
    assert(stats.lv_timer_us == 0 && stats.render.last.completed_ms == 2000);
    sample.completed_ms = 4000;
    sample.cycle_us = 100;
    sample.screen_switched = false;
    sample.refresh = {};
    sample.glyphs = {};
    window.render.add(sample);
    sample.flush = {};
    sample.glyphs = {10, 2, 1, 0, 50};
    sample.refresh.invalidations.add(1, 1, DisplayInvalidationSource::ScreenUpdate);
    window.render.add(sample);
    assert(window.publish(4500, stats));
    assert(stats.render.cycles == 2 && stats.render.last.cycle_us == 100);
    assert(stats.render.slowest.cycle_us == 6000000);
    assert(stats.render.navigations == 1 && stats.render.last_navigation.completed_ms == 2000);
    assert(stats.render.invalidations.requested_pixels == 10201);
    assert(stats.render.invalidations.calls[static_cast<unsigned>(DisplayInvalidationSource::ScreenUpdate)] == 1);
    assert(stats.render.glyphs.misses == 22 && stats.render.glyphs.miss_us == 350);
    assert(stats.render.last_navigation.glyphs.misses == 20);

    DisplayPresentationStats presentation;
    DisplayPresentationSample update;
    update.success = true;
    update.full = true;
    update.total_us = 500000;
    update.uploaded_bytes = 1314144;
    presentation.add(update);
    update.success = false;
    update.total_us = 1000000;
    presentation.add(update);
    update.success = true;
    update.full = false;
    update.total_us = 100000;
    presentation.add(update);
    assert(presentation.attempts == 3 && presentation.failures == 1);
    assert(presentation.full_updates == 1 && presentation.partial_updates == 1);
    assert(presentation.uploaded_bytes == uint64_t(1314144) * 3);
    assert(presentation.last.success && !presentation.slowest.success);
    assert(presentation.slowest.total_us == 1000000);
#endif
}