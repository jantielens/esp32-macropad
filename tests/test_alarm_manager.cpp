    assert(alarm_command_submit("cancel"));
    alarm_manager_loop();
    reboot(60 + 21600, true);
    assert(alarm_snapshot().state == ALARM_IDLE && dispatched.size() == 1);
    wall_clock = start;
    alarm_manager_loop();
    wall_clock += 600;
    alarm_manager_loop();
