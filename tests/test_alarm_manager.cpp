static uint64_t persisted_generation() {
    uint64_t newest = 0;
    for (const auto& file : storage_test_files) {
        JsonDocument document;
        if (!deserializeJson(document, file.second))
            newest = std::max(newest, document["generation"].as<uint64_t>());
    }
    return newest;
}

